    private void jButtonRegisterActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButtonRegisterActionPerformed
        // 1. Ambil input dari GUI
        String nama = jTextFieldNama.getText().trim();
        String noTelp = jTextFieldNoTelepon.getText().trim();
        String alamat = jTextFieldAlamat.getText().trim();
        String email = jTextFieldEmail.getText().trim();
        String password = new String(jPasswordFieldPassword.getPassword()).trim();
        // 2. Validasi input kosong di GUI
        if (nama.isEmpty() || noTelp.isEmpty() || alamat.isEmpty() || email.isEmpty() || password.isEmpty()) {
            jLabelLog.setText("Semua field wajib diisi!");
            jLabelLog.setForeground(java.awt.Color.RED);
            return;
        }
        try {
            // 3. Generate nomor keanggotaan unik (misal: MEM + timestamp)
            String membershipNumber = "MEM-" + System.currentTimeMillis();
            // 4. Panggil AuthService untuk registrasi
            authService.registerMember(nama, email, password, membershipNumber, alamat, noTelp);
            // 5. Jika sukses
            JOptionPane.showMessageDialog(this, "Registrasi Berhasil! Nomor Anggota Anda: " + membershipNumber,
                    "Sukses", JOptionPane.INFORMATION_MESSAGE);

            // Pindah ke form login dan tutup form register
            new FormLogin().setVisible(true);
            this.dispose();
        } catch (IllegalArgumentException e) {
            // Tangani jika email sudah terdaftar
            jLabelLog.setText(e.getMessage());
            jLabelLog.setForeground(java.awt.Color.RED);
        } catch (Exception e) {
            // Tangani error database/koneksi lainnya
            jLabelLog.setText("Terjadi kesalahan sistem: " + e.getMessage());
            jLabelLog.setForeground(java.awt.Color.RED);
        }
    }// GEN-LAST:event_jButtonRegisterActionPerformed

