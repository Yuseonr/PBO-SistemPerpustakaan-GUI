    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButtonLoginActionPerformed
        // 1. Ambil input dari GUI
        String email = jTextFieldEmail.getText().trim();
        String password = new String(jPasswordFieldPassword.getPassword()).trim();
        // 2. Validasi input kosong
        if (email.isEmpty() || password.isEmpty()) {
            jLabelLog.setText("Email dan Password tidak boleh kosong!");
            jLabelLog.setForeground(java.awt.Color.RED);
            return;
        }
        try {
            // 3. Panggil AuthService untuk login
            User loggedInUser = authService.login(email, password);
            // 4. Jika berhasil
            JOptionPane.showMessageDialog(this,
                    "Login Berhasil! Selamat Datang " + loggedInUser.getName(),
                    "Sukses", JOptionPane.INFORMATION_MESSAGE);
            // 5. TODO: Buka dashboard sesuai role, lalu tutup form login
            if (loggedInUser.getRole().equals(UserRole.MEMBER)) {
                new KatalogBuku().setVisible(true);
            } else if (loggedInUser.getRole().equals(UserRole.LIBRARIAN)) {
                new DashboardLibrarian().setVisible(true);
            } else if (loggedInUser.getRole().equals(UserRole.ADMIN)) {
                new AdminDashboardForm().setVisible(true);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Role tidak ditemukan",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
            this.dispose();
        } catch (IllegalArgumentException | IllegalStateException e) {
            // Email tidak ditemukan / password salah / akun nonaktif
            jLabelLog.setText(e.getMessage());
            jLabelLog.setForeground(java.awt.Color.RED);
        } catch (Exception e) {
            // Error koneksi database
            jLabelLog.setText("Gagal terhubung ke server.");
            jLabelLog.setForeground(java.awt.Color.RED);
        }
    }// GEN-LAST:event_jButtonLoginActionPerformed

