    private void loadRiwayatData() {
        if (loggedInUser == null) return;

        // 1. Ambil model tabel
        DefaultTableModel model = (DefaultTableModel) jTableRiwayat.getModel();
        model.setRowCount(0); // Kosongkan isi tabel sebelum diisi ulang

        // 2. Inisialisasi Repository
        ILoanTransactionRepository loanRepo = new LoanTransactionRepositoryMySQLImpl();

        // 3. Ambil data riwayat berdasarkan ID Member yang sedang login
        List<LoanTransaction> riwayat = loanRepo.findByMemberId(loggedInUser.getId());

        // 4. Masukkan data ke dalam tabel
        int no = 1;
        for (LoanTransaction txn : riwayat) {
            // Tanggal batas kembali (due date) bisa null jika statusnya CANCELLED
            String dueDateStr = (txn.getDueDate() != null) ? txn.getDueDate().toString() : "-";
            
            // Format denda menjadi string rupiah
            String denda = "Rp " + String.format("%,.0f", txn.getFineAmount());

            Object[] row = {
                no++,
                txn.getBookCopy().getBookTitle().getTitle(),
                txn.getRequestDate().toLocalDate().toString(), // Tanggal Pinjam
                dueDateStr,                                    // Batas Kembali
                txn.getStatus().name(),                        // Status
                denda                                          // Denda
            };
            model.addRow(row);
        }
    }


