    private void loadDataKategori() {
        categoryList = catRepo.findAll();
        DefaultTableModel model = (DefaultTableModel) jTableKategori.getModel();
        model.setRowCount(0);
        int no = 1;
        for (Category cat : categoryList) {
            model.addRow(new Object[]{
                no++,
                cat.getName(),
                cat.getDescription()
            });
        }
    }
