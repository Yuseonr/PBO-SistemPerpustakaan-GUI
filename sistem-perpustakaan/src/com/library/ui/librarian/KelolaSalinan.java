    private void loadDataSalinan() {
        // 1. Ambil data salinan HANYA untuk buku induk yang dipilih
        copyList = copyRepo.findByBookTitleId(parentBook.getId());

        // 2. Kosongkan tabel
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTableSalinan.getModel();
        model.setRowCount(0); 

        // 3. Looping data dan masukkan ke tabel
        for (com.library.domain.entities.BookCopy copy : copyList) {
            model.addRow(new Object[]{
                copy.getId(),
                copy.getLocation(),
                copy.getStatus().name() // name() mengubah Enum menjadi String teks
            });
        }
    }
