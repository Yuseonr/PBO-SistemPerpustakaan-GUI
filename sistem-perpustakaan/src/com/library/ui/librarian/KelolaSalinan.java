    private void jButtonTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahActionPerformed
        String lokasi = jTextFieldLokasi.getText();
        int jumlah = (Integer) jSpinnerJumlah.getValue();
        if (lokasi.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lokasi rak harus diisi!");
            return;
        }
        if (jumlah <= 0) {
            JOptionPane.showMessageDialog(this, "Jumlah salinan minimal 1!");
            return;
        }
        for (int i = 0; i < jumlah; i++) {
            BookCopy newCopy = new BookCopy(null, lokasi, parentBook);
            newCopy.setStatus(com.library.domain.enums.BookCopyStatus.AVAILABLE);
            copyRepo.save(newCopy);
        }
        JOptionPane.showMessageDialog(this, jumlah + " salinan berhasil ditambahkan!");
        jTextFieldLokasi.setText(""); // kosongkan inputan
        loadDataSalinan();
    }//GEN-LAST:event_jButtonTambahActionPerformed

    private void jTableSalinanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableSalinanMouseClicked
        int barisTerpilih = jTableSalinan.getSelectedRow();
        if (barisTerpilih != -1) {
            BookCopy selectedCopy = copyList.get(barisTerpilih);
            jTextFieldLokasi.setText(selectedCopy.getLocation());
        }
    }//GEN-LAST:event_jTableSalinanMouseClicked

    private void jButtonPerbaruiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPerbaruiActionPerformed
        int barisTerpilih = jTableSalinan.getSelectedRow();
        if (barisTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih salinan yang ingin diperbarui dari tabel!");
            return;
        }
        
        BookCopy selectedCopy = copyList.get(barisTerpilih);
        selectedCopy.setLocation(jTextFieldLokasi.getText());
        copyRepo.update(selectedCopy);
        
        JOptionPane.showMessageDialog(this, "Lokasi salinan berhasil diperbarui!");
        jTextFieldLokasi.setText("");
        loadDataSalinan();
    }//GEN-LAST:event_jButtonPerbaruiActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        int barisTerpilih = jTableSalinan.getSelectedRow();
        if (barisTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih salinan yang ingin dihapus dari tabel!");
            return;
        }
        
        BookCopy selectedCopy = copyList.get(barisTerpilih);
        
        // Cek jika buku sedang dipinjam
        if (selectedCopy.getStatus() == com.library.domain.enums.BookCopyStatus.LOANED || 
            selectedCopy.getStatus() == com.library.domain.enums.BookCopyStatus.RESERVED) {
            JOptionPane.showMessageDialog(this, "Salinan tidak bisa dihapus karena sedang dipinjam atau dipesan!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus fisik buku ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            copyRepo.delete(selectedCopy.getId());
            JOptionPane.showMessageDialog(this, "Salinan berhasil dihapus!");
            jTextFieldLokasi.setText("");
            loadDataSalinan();
        }
    }//GEN-LAST:event_jButtonHapusActionPerformed

